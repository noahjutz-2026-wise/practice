from collections.abc import Callable

import numpy as np
from numpy.random import Generator
from numpy.typing import NDArray

from gym_app.policy import Policy


def isr(pi: Policy, b: Policy, a: int, s: tuple[int, int, int, int]) -> float:
    """
    One factor of the Incremental Importance-Sampling Ratio for
    - an epsilon-greedy behavior policy b
    - a greedy target policy pi
    with the same state-action values Q.

    Args:
        pi: Target policy
        b: Behavior policy
        a: Action
        s: State
    Returns:
        pi(a | s)/b(a | s). To get the ISR rho_(t:T-1), create product over all time steps.
    """

    if pi.p(a, s) == 0:
        return 0
    return pi.p(a, s) / b.p(a, s)


def monte_carlo(
    rewards: NDArray[np.float64],
    states: NDArray[np.uint32],
    actions: NDArray[np.uint32],
    gamma: float,
    epsilon: float,
    C: NDArray,
    Q: NDArray,
    pi: Policy,
    b: Policy,
) -> tuple[NDArray, NDArray]:
    """
    First-Visit MC prediction for pi, given one T-step episode generated by b, using weighted importance sampling
    Args:
        rewards: (T,)
        states: (T, 4)
        actions: (T,)
        gamma: Discount factor
        epsilon: Exploring Rate
        C: (*n_bins, 2) Cumulative weight for each state
        Q: (*n_bins, 2) state-action value
        pi: Target policy
        b: Behavior policy
    Returns:
        C, Q
    """
    T = len(rewards)
    # Build set of first-visit timesteps: for each (state, action) pair,
    # only the earliest timestep counts.
    first_visit: dict[tuple, int] = {}
    for t in range(T):
        key = (*states[t], actions[t])
        if key not in first_visit:
            first_visit[key] = t

    # Backward pass to compute returns
    G = 0.0
    W = 1
    for t in range(T - 1, -1, -1):
        G = gamma * G + rewards[t]

        key = (*states[t], actions[t])
        if first_visit[key] == t:
            idx = tuple(key)
            C[idx] += W
            Q[idx] += (W / C[idx]) * (G - Q[idx])

        W *= isr(pi, b, actions[t], states[t])
        if W == 0:
            break
    return C, Q


def sarsa(
    Q: NDArray[np.float64],
    alpha: float,
    gamma: float,
    old_sa: tuple[int, int, int, int, int],
    sa: tuple[int, int, int, int, int],
    r: float,
    is_T: bool,
) -> NDArray:
    """
    Sarsa (tabular, one-step TD, on-policy).

    Args:
        Q: (*n_bins, 2) state-action value estimate
        alpha: Step size
        gamma: Discount factor
        old_sa: state-action pair at step t
        sa: state-action pair at step (t+1)
        r: reward at step (t+1)
    Returns:
        Q: (*n_bins, 2) next state_action value estimate
    """

    error = r + gamma * Q[sa] * (1 - is_T) - Q[old_sa]
    Q[old_sa] = Q[old_sa] + alpha * error
    return Q


def q_learning(
    Q1: NDArray[np.float64],
    alpha: float,
    gamma: float,
    old_sa: tuple[int, int, int, int, int],
    sa: tuple[int, int, int, int, int],
    r: float,
    is_T: bool,
    random: Generator,
    Q2: NDArray[np.float64] | None = None,
) -> NDArray:
    """
    Q-learning (tabular, one-step TD, off-policy)

    Args:
        Q1: (*n_bins, 2) state-action value estimate
        alpha: Step size
        gamma: Discount factor
        old_sa: state-action pair at step t
        sa: state-action pair at step (t+1)
        r: reward at step (t+1)
        is_T: True if this step is the last before termination
        random: Numpy RNG
        Q2: (*n_bins, 2) state-action value estimate for double learning. Pass None to disable.
    Returns:
        Q1: (*n_bins, 2) next state_action value estimate
        Q2: (*n_bins, 2) next state_action value estimate
    """
    s = sa[:-1]
    pair = [Q1, Q2 if Q2 is not None else Q1]
    random.shuffle(pair)
    Qa, Qb = pair

    greedy_a = np.argmax(Qa[s])
    greedy_v = Qb[(*s, greedy_a)]
    error = r + gamma * greedy_v * (1 - is_T) - Qa[old_sa]
    Qa[old_sa] += alpha * error
    return Q1, Q2


def expected_sarsa(
    Q: NDArray[np.float64],
    alpha: float,
    gamma: float,
    old_sa: tuple[int, int, int, int, int],
    sa: tuple[int, int, int, int, int],
    r: float,
    is_T: bool,
    pi: Policy,
) -> NDArray:
    """
    Move towards expectation

    Args:
        Q: (*n_bins, 2) state-action value estimate
        alpha: Step size
        gamma: Discount factor
        old_sa: state-action pair at step t
        sa: state-action pair at step (t+1)
        r: reward at step (t+1)
        is_T: True if this step is the last before termination
        pi: Target policy
    Returns:
        Q: (*n_bins, 2) next state_action value estimate
    """

    s = sa[:-1]
    expected_q = 0
    for a in range(2):
        p = pi.p(a, s)
        q = Q[(*s, a)]
        expected_q += p * q

    error = r + gamma * expected_q * (1 - is_T) - Q[old_sa]
    Q[old_sa] += alpha * error
    return Q


def n_step_td(
    Q: NDArray[np.float64],
    alpha: float,
    gamma: float,
    sa: tuple[int, int, int, int, int],
    r: NDArray,
    is_T: bool,
    n: int,
):
    """
    Args:
        Q: (*n_bins, 2) state-action value estimate
        alpha: Step size
        gamma: Discount factor
        sa: state-action pair at step (t+1)
        r: last n rewards (t-n+1,...,t+1)
        is_T: True if this step is the last before termination
        n: Look n steps ahead
    Returns:
        Q: (*n_bins, 2) next state_action value estimate
    """
    r = r[:-n]

    G = 0
    for i in range(n):
        G += gamma**i * r[i]
    if not is_T:
        G += gamma**n * Q[sa]

    Q[sa] += alpha * (G - Q[sa])
